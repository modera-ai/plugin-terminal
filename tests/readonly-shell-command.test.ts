import { expect, it } from "vitest";
import { isReadonlyShellCommand } from "../src/readonly-shell-command";

it.each([
  "ls -la",
  "pwd",
  "find . -maxdepth 2 -type d",
  "ls -la /tmp | head -20",
  "find . -name '*.ts' -print | sort | head -n 20",
  "cd '/a path' && ls -la",
  "set -euo pipefail; pwd; ls",
  "set -x && ls",
  "ls missing 2>/dev/null || true",
  "ls 2>&1",
  "ls >/dev/null",
  "ls;\npwd",
  "# inspect\nls -la",
  "cat 'semi;colon.txt'",
  "printf '%s\\n' '$(literal)'",
  "sed -n '1,200p' file",
  "sed -n '1,$p' file",
  "git -C /tmp status --short",
  "git diff --stat",
  "git branch --list 'main*'",
  "git config --get remote.origin.url",
  "rg --files",
  "rg -n 'word' .",
  "ls \\\n -la",
  "ls 'quoted>filename'",
  "test -d src && ls src",
])("skips optional snapshots for read-only shell command %s", (command) => {
  expect(isReadonlyShellCommand(command)).toBe(true);
});
it.each([
  "ls; rm file",
  "ls && touch file",
  "ls || mkdir missing",
  "ls\nrm file",
  "ls > output",
  "ls >> output",
  "ls >/dev/null-not-a-device",
  "ls > /dev/null/file",
  "ls | tee output",
  "ls | sh",
  "ls $(touch file)",
  'ls "$(touch file)"',
  "echo `touch file`",
  "# comment\ntouch file",
  "ls 'unterminated",
  "ls \\",
  "find . -delete",
  "find . -exec touch file \\;",
  "find . -fprint output",
  "sort -ooutput input",
  "sort --output=output input",
  "uniq input output",
  "sed -i s/a/b/ file",
  "sed -n '1w output' file",
  "sed -f script file",
  "sed -n '1p' file -e 'e touch output'",
  "git tag --list --delete tag",
  "find . -fls output",
  "git branch new-branch",
  "git tag new-tag",
  "git remote add x url",
  "git reflog expire --all",
  "git diff --output=out",
  "git -c diff.external=tool diff",
  "rg --pre=script pattern .",
  "node script.js",
  "python -c 'print(1)'",
  "sh -c 'ls'",
  "source config; ls",
  "for f in *; do cat file; done",
  "ls < input",
  "ls >(cat)",
  "eval ls",
  "COMMAND=rm; $COMMAND file",
  "",
])(
  "retains optional snapshots for unknown or mutating shell command %s",
  (command) => {
    expect(isReadonlyShellCommand(command)).toBe(false);
  },
);
